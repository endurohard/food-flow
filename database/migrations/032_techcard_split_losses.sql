-- ============================================================
-- Миграция 032: Раздельные потери в техкарте (брутто → нетто → выход)
-- ============================================================
-- Было: одно поле waste_percent на весь процесс. Этого не хватает для
-- реального производства: картофель сначала чистят (холодная обработка),
-- потом варят (горячая). Проценты разные, и считаются от разных величин.
-- С одним числом нельзя одновременно правильно посчитать закупку
-- (нужно брутто) и выход порции (нужен вес после готовки).
--
-- Стало, как в профессиональных системах учёта:
--   брутто  — сколько взяли со склада (по нему идёт списание и себестоимость)
--   нетто   — после холодной обработки: брутто × (1 - cold_loss/100)
--   выход   — после горячей:            нетто  × (1 - hot_loss/100)
--
-- ВАЖНО о смысле quantity:
-- после этой миграции tech_card_ingredients.quantity — это БРУТТО.
-- Раньше оно вело себя как «нетто», а расход считался как
-- quantity * (1 + waste_percent/100).
--
-- Здесь же исправляется ошибка старой формулы. Процент потерь берётся
-- от БРУТТО, поэтому обратный пересчёт — деление, а не умножение:
--   верно:    брутто = нетто / (1 - p/100)
--   было:     брутто = нетто * (1 + p/100)
-- При 20% потерь на 1 кг нетто нужно 1.25 кг брутто, а списывалось 1.2 —
-- недосписание 4%, которое копилось при каждой продаже.
--
-- Миграция сохраняет ФАКТИЧЕСКОЕ количество списания один в один
-- (brutto := quantity * (1 + waste/100)), а проценты пересчитывает так,
-- чтобы прежнее «нетто» осталось прежним. Остатки на складе не поедут,
-- себестоимость не скакнёт: меняется только смысл полей, не числа.
--
-- Идемпотентна: безопасно запускать повторно.
-- Date: 2026-10-20

-- ── 1. Новые поля ───────────────────────────────────────────────────────────
ALTER TABLE tech_card_ingredients
    ADD COLUMN IF NOT EXISTS cold_loss_percent DECIMAL(5, 2) NOT NULL DEFAULT 0
        CHECK (cold_loss_percent >= 0 AND cold_loss_percent < 100);

ALTER TABLE tech_card_ingredients
    ADD COLUMN IF NOT EXISTS hot_loss_percent DECIMAL(5, 2) NOT NULL DEFAULT 0
        CHECK (hot_loss_percent >= 0 AND hot_loss_percent < 100);

COMMENT ON COLUMN tech_card_ingredients.quantity IS
    'Брутто: сколько берётся со склада. По нему идёт списание и себестоимость.';
COMMENT ON COLUMN tech_card_ingredients.cold_loss_percent IS
    'Потери холодной обработки, % от брутто (чистка, зачистка, разделка).';
COMMENT ON COLUMN tech_card_ingredients.hot_loss_percent IS
    'Потери горячей обработки, % от нетто (варка, жарка, запекание).';

-- ── 2. Перенос данных из waste_percent ──────────────────────────────────────
-- Выполняется один раз: признак — waste_percent ещё существует и ненулевой,
-- а новые поля нетронуты. Повторный запуск ничего не меняет.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tech_card_ingredients' AND column_name = 'waste_percent'
    ) THEN
        UPDATE tech_card_ingredients
        SET
            -- Брутто = прежний фактический расход. Списание не меняется.
            quantity = ROUND((quantity * (1 + COALESCE(waste_percent, 0) / 100.0))::numeric, 3),
            -- Процент, при котором нетто останется прежним:
            -- нетто = брутто * (1 - p/100)  →  p = 100 * waste / (100 + waste)
            cold_loss_percent = ROUND((100.0 * COALESCE(waste_percent, 0)
                                       / (100.0 + COALESCE(waste_percent, 0)))::numeric, 2)
        WHERE COALESCE(waste_percent, 0) > 0
          AND cold_loss_percent = 0
          AND hot_loss_percent = 0;

        -- Старое поле оставляем: откат миграции не должен терять данные.
        -- Код его больше не читает.
        COMMENT ON COLUMN tech_card_ingredients.waste_percent IS
            'УСТАРЕЛО (миграция 032). Заменено на cold_loss_percent / hot_loss_percent. Не используется кодом.';
    END IF;
END $$;
