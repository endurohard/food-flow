-- ============================================================
-- Миграция 048: PIN кассира для режима кассы
-- ============================================================
-- PIN хранится отдельно от password_hash, в виде bcrypt-хеша.
-- Используется для входа в режим кассы (после email+пароля) и
-- для блокировки/разблокировки кассы.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS pin_hash VARCHAR(255) NULL;
