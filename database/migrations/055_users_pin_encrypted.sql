-- ============================================================
-- Миграция 055: PIN можно посмотреть в кабинете владельца
-- ============================================================
-- Проверка PIN по-прежнему идёт по bcrypt-хешу (pin_hash). Рядом хранится
-- копия PIN, зашифрованная ENCRYPTION_KEY user-service (AES-256-GCM, как
-- пароль ВАТС), — чтобы владелец или админ мог подсмотреть забытый PIN
-- кассира и свой в «Устройствах». Ключ шифрования в базе не хранится.
-- У PIN, заданных до этой миграции, копии нет — их нужно задать заново.

ALTER TABLE users ADD COLUMN IF NOT EXISTS pin_encrypted TEXT;
