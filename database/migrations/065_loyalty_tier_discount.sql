-- ============================================================
-- Миграция 065: скидка по уровню карты лояльности и позиции без скидки
-- ============================================================
-- * loyalty_programs.tier_discounts — процент скидки по уровню карты клиента:
--   {"bronze": 3, "silver": 5, "gold": 10, "platinum": 15}. Целые 0..100:
--   касса (Sigma, оффлайн) считает скидку в копейках сама, и результат обязан
--   совпасть с сервером до копейки — дробные проценты дали бы расхождения.
-- * menu_items.no_discount — позиция, на которую скидки не действуют
--   (ни по карте, ни акции «на весь чек»): например, товары с фиксированной
--   ценой. Доплата за модификатор (сорт) идёт вместе со своей позицией.
-- Идемпотентна.

ALTER TABLE loyalty_programs ADD COLUMN IF NOT EXISTS tier_discounts JSONB NOT NULL DEFAULT '{}';
ALTER TABLE menu_items      ADD COLUMN IF NOT EXISTS no_discount BOOLEAN NOT NULL DEFAULT false;
