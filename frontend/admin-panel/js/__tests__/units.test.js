/** Отображение количеств: хранение в кг, показ в граммах. */
const U = require('../units.js');

describe('formatQty: перевод в мелкую единицу', () => {
  it('доли килограмма показываются граммами, как в iiko', () => {
    expect(U.qty(0.014, 'кг')).toBe('14 г');
    expect(U.qty(0.022, 'кг')).toBe('22 г');
    expect(U.qty(0.0015, 'кг')).toBe('1,5 г');
  });

  it('килограмм и больше остаётся килограммами', () => {
    expect(U.qty(1, 'кг')).toBe('1 кг');
    expect(U.qty(7.2, 'кг')).toBe('7,2 кг');
    expect(U.qty(6, 'кг')).toBe('6 кг');
  });

  it('литры переводятся в миллилитры по тому же правилу', () => {
    expect(U.qty(0.25, 'л')).toBe('250 мл');
    expect(U.qty(1.5, 'л')).toBe('1,5 л');
  });

  it('штуки не переводятся никуда', () => {
    expect(U.qty(2, 'шт')).toBe('2 шт');
    expect(U.qty(0.5, 'шт')).toBe('0,5 шт');
  });

  it('ноль показывается в базовой единице, а не «0 г»', () => {
    // «0 г» в пустой строке состава сбивает с толку
    expect(U.qty(0, 'кг')).toBe('0 кг');
  });
});

describe('Точность и формат', () => {
  it('хвостовые нули не выводятся', () => {
    expect(U.qty(0.014, 'кг')).not.toContain('14,000');
    expect(U.qty(2, 'шт')).toBe('2 шт');
  });

  it('разделитель — запятая, как во всей админке', () => {
    expect(U.qty(7.2, 'кг')).toBe('7,2 кг');
    expect(U.qty(7.2, 'кг')).not.toContain('.');
  });

  it('само значение не меняется — пересчёт только для показа', () => {
    const r = U.formatQty(0.014, 'кг');
    expect(r.value).toBeCloseTo(14, 9);
    expect(r.unit).toBe('г');
    // исходное число не трогаем
    const src = 0.014;
    U.formatQty(src, 'кг');
    expect(src).toBe(0.014);
  });

  it('мелкие доли не схлопываются в ноль', () => {
    // 0,0015 кг = 1,5 г: при округлении до 3 знаков в КГ это было бы «0,002»
    expect(U.qty(0.0015, 'кг')).toBe('1,5 г');
  });

  it('отрицательные значения (возвраты) не ломают правило', () => {
    expect(U.qty(-0.014, 'кг')).toBe('-14 г');
  });
});

describe('Устойчивость к мусору', () => {
  it('пустое и нечисловое дают прочерк, а не NaN на экране', () => {
    expect(U.qty(null, 'кг')).toBe('—');
    expect(U.qty(undefined, 'кг')).toBe('—');
    expect(U.qty('', 'кг')).toBe('—');
    expect(U.qty('abc', 'кг')).toBe('—');
  });

  it('число строкой из API работает как число', () => {
    expect(U.qty('0.014', 'кг')).toBe('14 г');
  });

  it('неизвестная единица выводится как есть', () => {
    expect(U.qty(0.5, 'порц')).toBe('0,5 порц');
    expect(U.qty(3, '')).toBe('3');
  });
});
