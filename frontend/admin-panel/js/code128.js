/**
 * Code128 без внешних библиотек — штрихкод номера карты гостя.
 *
 * Зачем рядом с QR: ручной шаблон карты в Apple Wallet («Создать карту»),
 * Google Wallet, «Кошелёк» и многие кассовые сканеры-клавиатуры читают
 * линейный штрихкод надёжнее или только его. Номер карты — 8 цифр, поэтому
 * для чётного числа цифр берётся набор C (две цифры на символ, код короче и
 * читается с экрана с большего расстояния), иначе — набор B (печатный ASCII).
 *
 * Модуль грузится и тегом <script> (window.Code128), и require из тестов.
 */
(function (root) {
  // Ширины полос/пробелов (в модулях) для значений 0..105 и стоп-символа.
  // Каждый символ — 11 модулей, стоп — 13. Таблица по ISO/IEC 15417.
  var PATTERNS = [
    '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312', '132212', '221213',
    '221312', '231212', '112232', '122132', '122231', '113222', '123122', '123221', '223211', '221132',
    '221231', '213212', '223112', '312131', '311222', '321122', '321221', '312212', '322112', '322211',
    '212123', '212321', '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
    '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121', '313121', '211331',
    '231131', '213113', '213311', '213131', '311123', '311321', '331121', '312113', '312311', '332111',
    '314111', '221411', '431111', '111224', '111422', '121124', '121421', '141122', '141221', '112214',
    '112412', '122114', '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
    '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112', '421211', '212141',
    '214121', '412121', '111143', '111341', '131141', '114113', '114311', '411113', '411311', '113141',
    '114131', '311141', '411131', '211412', '211214', '211232', '2331112'
  ];
  var START_B = 104, START_C = 105, STOP = 106;

  /** Значения символов (со стартом и контрольным, без стопа). */
  function values(text) {
    text = String(text);
    if (!text.length) throw new Error('Пустой текст для штрихкода');
    var out;
    if (/^\d+$/.test(text) && text.length % 2 === 0) {
      out = [START_C];
      for (var i = 0; i < text.length; i += 2) out.push(parseInt(text.substr(i, 2), 10));
    } else {
      out = [START_B];
      for (var j = 0; j < text.length; j++) {
        var code = text.charCodeAt(j);
        if (code < 32 || code > 126) throw new Error('Code128-B: символ вне печатного ASCII');
        out.push(code - 32);
      }
    }
    // Контрольный: старт + Σ(позиция × значение), по модулю 103
    var sum = out[0];
    for (var k = 1; k < out.length; k++) sum += k * out[k];
    out.push(sum % 103);
    return out;
  }

  /** Строка ширин полос и пробелов, начиная с полосы, включая стоп. */
  function widths(text) {
    return values(text).map(function (v) { return PATTERNS[v]; }).join('') + PATTERNS[STOP];
  }

  /**
   * SVG-разметка штрихкода. Тихие зоны по 10 модулей слева и справа
   * обязательны: без них сканер не находит начало кода.
   */
  function svg(text, opts) {
    opts = opts || {};
    var height = opts.height || 60;
    var quiet = 10;
    var w = widths(text);
    var x = quiet, d = '';
    for (var i = 0; i < w.length; i++) {
      var n = +w[i];
      if (i % 2 === 0) d += 'M' + x + ' 0h' + n + 'v' + height + 'h-' + n + 'z';
      x += n;
    }
    var total = x + quiet;
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + total + ' ' + height +
      '" preserveAspectRatio="none" shape-rendering="crispEdges" role="img">' +
      '<rect width="' + total + '" height="' + height + '" fill="#fff"/>' +
      '<path d="' + d + '" fill="#000"/></svg>';
  }

  var api = { values: values, widths: widths, svg: svg, PATTERNS: PATTERNS };
  if (typeof window !== 'undefined') window.Code128 = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(this);
